// 📚 The docs source (0.2.24): fumadocs-core's headless `loader()` over the compiled MDX collection (`.source/`),
// with one page tree per locale. `parser: 'dir'` = `content/docs/<locale>/…`; a page missing in fr / es / ru falls
// back to the English one (fumadocs' `fallbackLanguage`, default = `defaultLanguage`), the page shows a banner 🏳️.
// `hideLocale: 'default-locale'` matches our `localePrefix: 'as-needed'` (`/docs` in English, `/fr/docs` …) 🌍.

// import the compiled docs collection (generated by fumadocs-mdx) 📦
import { docs } from 'collections/server';
// import fumadocs' headless loader & i18n helper (no fumadocs-ui) 🧱
import { loader } from 'fumadocs-core/source';
import { defineI18n } from 'fumadocs-core/i18n';
// import abElements' i18n config (the single source of truth for locales) 🌐
import abI18nConfig from '@/i18n/config';
// import the docs base path 🧭
import { DOCS_BASE } from '@/lib/docs';


// 🌍 fumadocs' i18n config, derived from ours (never a second locale list)
export const docsI18n = defineI18n({
  languages: [...abI18nConfig.locales],
  defaultLanguage: abI18nConfig.defaultLocale,
  // 📂 `content/docs/en/…`, `content/docs/fr/…`
  parser: 'dir',
  // 🫥 no `/en` prefix (as-needed)
  hideLocale: 'default-locale',
});


// 📚 the docs source: pages, page trees & URLs per locale
export const source = loader({
  baseUrl: DOCS_BASE,
  source: docs.toFumadocsSource(),
  i18n: docsI18n,
});
